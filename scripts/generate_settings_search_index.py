#!/usr/bin/env python3
"""Generates SettingsSearchIndex.kt: every settings row with a fixed title, and where it lives.

Run from the repository root after adding or moving settings rows:

    python3 scripts/generate_settings_search_index.py

Rows are found by `title = stringResource(R.string.x)` and, if present, the `subtitle` that follows
in the same call. A row's page comes from its file, and for playback settings from the section
function it is in. Rows whose title is built at runtime are not indexed.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SETTINGS = ROOT / "app/src/main/java/com/nuvio/tv/ui/screens/settings"
PARTY = ROOT / "app/src/main/java/com/nuvio/tv/ui/screens/party"
OUTPUT = SETTINGS / "SettingsSearchIndex.kt"

# file -> (page, integration sub-section or None)
FILE_PAGES = {
    "ThemeSettingsScreen.kt": ("APPEARANCE", None),
    "AmbientModeSettings.kt": ("APPEARANCE", None),
    "LayoutHomeSettings.kt": ("LAYOUT", None),
    "LayoutCardSettings.kt": ("LAYOUT", None),
    "LayoutDetailSettings.kt": ("LAYOUT", None),
    "PlaybackPlayerSettings.kt": ("PLAYBACK", None),
    "PlaybackAutoPlaySettings.kt": ("PLAYBACK", None),
    "PlaybackAudioSettings.kt": ("PLAYBACK", None),
    "PlaybackVideoSettings.kt": ("PLAYBACK", None),
    "PlaybackBufferNetworkSettings.kt": ("PLAYBACK", None),
    "PlaybackP2pSettings.kt": ("PLAYBACK", None),
    "PlaybackSubtitleSettings.kt": ("SUBTITLES", None),
    "SubtitleTranslationSettingsItems.kt": ("SUBTITLES", None),
    "AutoSyncSettingsItems.kt": ("SUBTITLES", None),
    "ContentDiscoverySettingsContent.kt": ("CONTENT_DISCOVERY", None),
    "MediaServerSettingsScreen.kt": ("CONTENT_DISCOVERY", None),
    "MediaServersSettingsScreen.kt": ("CONTENT_DISCOVERY", None),
    "DebridSettingsScreen.kt": ("INTEGRATION", "Debrid"),
    "TmdbSettingsScreen.kt": ("INTEGRATION", "Tmdb"),
    "MDBListSettingsScreen.kt": ("INTEGRATION", "MdbList"),
    "MdbListLibraryListsDialog.kt": ("INTEGRATION", "MdbList"),
    "AnimeSkipSettingsScreen.kt": ("INTEGRATION", "AnimeSkip"),
    "TrackingSettingsScreen.kt": ("TRACKING", None),
    "NetworkSettingsScreen.kt": ("ADVANCED", None),
    "AboutScreen.kt": ("ABOUT", None),
    "UpdateChannelSettings.kt": ("ABOUT", None),
    "ProfileSettingsContent.kt": ("PROFILES", None),
}
PARTY_FILES = {"PartySettingsContent.kt": ("WATCH_PARTY", None)}

# playback section function -> PlaybackSection
SECTION_FUNCTIONS = {
    "PlaybackPlayerSection": "PLAYER",
    "PlaybackSkipSegmentsSection": "SKIP_SEGMENTS",
    "AutoSkipToggle": "SKIP_SEGMENTS",
    "PlaybackPlayerInterfaceSection": "PLAYER_INTERFACE",
    "PlaybackStreamSelectionSection": "STREAM_SELECTION",
    "PlaybackUpNextSection": "UP_NEXT",
    "PlaybackAudioSection": "AUDIO",
    "PlaybackVideoSection": "VIDEO",
    "PlaybackBufferNetworkSection": "BUFFER_NETWORK",
    "CustomBufferControls": "BUFFER_NETWORK",
    "DiskCacheControls": "BUFFER_NETWORK",
    "ParallelNetworkControls": "BUFFER_NETWORK",
    "PlaybackP2pSection": "P2P",
}

TITLE = re.compile(r"(?<![A-Za-z])title\s*=\s*stringResource\(\s*R\.string\.(\w+)\s*\)")
SUBTITLE = re.compile(r"(?<![A-Za-z])(?:subtitle|description)\s*=\s*stringResource\(\s*R\.string\.(\w+)\s*\)")
FUNCTION = re.compile(r"\bfun\s+(?:<[^>]*>\s*)?(\w+)\s*\(")


def rows(path: Path):
    text = path.read_text(encoding="utf-8")
    functions = [(m.start(), m.group(1)) for m in FUNCTION.finditer(text)]
    titles = list(TITLE.finditer(text))
    for index, match in enumerate(titles):
        end = titles[index + 1].start() if index + 1 < len(titles) else len(text)
        window = text[match.end():min(end, match.end() + 400)]
        subtitle = SUBTITLE.search(window)
        function = next((name for start, name in reversed(functions) if start < match.start()), "")
        yield match.group(1), subtitle.group(1) if subtitle else None, function


def main():
    entries, seen = [], set()
    sources = [(SETTINGS / name, page) for name, page in FILE_PAGES.items()]
    sources += [(PARTY / name, page) for name, page in PARTY_FILES.items()]
    for path, (page, integration) in sources:
        if not path.exists():
            continue
        for title, subtitle, function in rows(path):
            # Choice dialogs repeat the title of the row that opens them.
            if function.endswith("Dialog") or function.endswith("Dialogs"):
                continue
            section = SECTION_FUNCTIONS.get(function) if page == "PLAYBACK" else None
            if page == "SUBTITLES":
                section = "SUBTITLES"
            key = (title, page)
            if key in seen:
                continue
            seen.add(key)
            entries.append((title, subtitle, page, section, integration))

    lines = [
        "// Generated by scripts/generate_settings_search_index.py. Do not edit by hand.",
        "package com.nuvio.tv.ui.screens.settings",
        "",
        "import com.nuvio.tv.R",
        "",
        "internal val settingsSearchIndex: List<SettingsSearchEntry> = listOf(",
    ]
    for title, subtitle, page, section, integration in entries:
        args = [f"R.string.{title}", f"R.string.{subtitle}" if subtitle else "null", f"SettingsCategory.{page}"]
        args.append(f"PlaybackSection.{section}" if section else "null")
        args.append(f"SettingsSearchIntegration.{integration}" if integration else "null")
        lines.append(f"    SettingsSearchEntry({', '.join(args)}),")
    lines.append(")")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(entries)} settings indexed -> {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
